"""One line per top-level function and class of code3d/lib (block B4 of docs/current/reports/architecture-second-opinion-2026-11-11.md, P12).

A creative session plans reuse in a production's notes.md ("Reuse plan") from this index and assets/patterns.md, without reading the rig libraries.
Static: the files are parsed with ast, never imported (they need bpy).
usage: .venv/bin/python tools/lib_index.py            # writes code3d/lib/INDEX.md
       .venv/bin/python tools/lib_index.py --check    # exit 1 when INDEX.md is out of date"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "code3d" / "lib"
OUT = LIB / "INDEX.md"


def first_line(node) -> str:
    doc = ast.get_docstring(node) or ""
    return " ".join(doc.strip().split("\n")[0].split())[:160]


def signature(fn: ast.FunctionDef) -> str:
    a = fn.args
    names = [x.arg for x in a.posonlyargs + a.args]
    if a.vararg:
        names.append("*" + a.vararg.arg)
    names += [x.arg for x in a.kwonlyargs]
    if a.kwarg:
        names.append("**" + a.kwarg.arg)
    return f"{fn.name}({', '.join(names)})"


def entries(path: Path) -> tuple[str, list[str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    out = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            out.append(f"- `{signature(node)}` {first_line(node)}".rstrip())
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            methods = [m.name for m in node.body if isinstance(m, ast.FunctionDef) and not m.name.startswith("_")]
            more = f" methods: {', '.join(methods)}" if methods else ""
            out.append(f"- class `{node.name}` {first_line(node)}{more}".rstrip())
    return first_line(tree), out


def render() -> str:
    lines = ["# code3d/lib index (generated by tools/lib_index.py; do not edit by hand)", "",
             "One line per public top-level function and class, with the first docstring line. Plan reuse from here and `assets/patterns.md`;",
             "read a library only for the functions a plan names. Regenerate after adding or changing a library.", ""]
    for path in sorted(LIB.glob("*.py")):
        if path.name == "__init__.py":
            continue
        doc, items = entries(path)
        lines.append(f"## {path.name}" + (f": {doc}" if doc else ""))
        lines += items or ["- (no public top-level functions)"]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("code3d/lib/INDEX.md is current" if ok else "code3d/lib/INDEX.md is out of date: run .venv/bin/python tools/lib_index.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
